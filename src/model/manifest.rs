//! `mods.lock.toml`: the list of the pack's mods.
//!
//! Each entry is a superset of a `files[]` entry of a `.mrpack` (`path`,
//! `hashes`, `fileSize`, `env`, `downloads`), plus the stable `key` variants refer
//! to, an optional direct `url`, the `source` of a local mod and its
//! approval, and one free table per platform. The core
//! stores platform tables without reading them; only the platform named by the
//! table does.
//!
//! The file is generated, never edited by hand. Writing is deterministic:
//! entries sorted by key, fields in a fixed order, so that reading then writing
//! an unchanged manifest gives the same bytes and adding a mod only adds its
//! own lines to the diff.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::error::{Error, Result};

/// File name of the manifest, at the root of the repository.
pub const FILE_NAME: &str = "mods.lock.toml";

const HEADER: &str = "# Generated by modpack-cli. Do not edit by hand: run `modpack manifest`.\n\n";
const HINT: &str = "regenerate it with `modpack manifest`";

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Manifest {
    pub pack: Pack,
    #[serde(default)]
    pub mods: Vec<Entry>,
}

/// What the pack runs on, after the `dependencies` of a `.mrpack`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub struct Pack {
    /// Minecraft version, such as `1.21.1`.
    pub minecraft: String,
    /// Loader, as Modrinth names it: `neoforge`, `fabric`, `forge`, `quilt`.
    pub loader: String,
    pub loader_version: String,
}

/// One mod. Fields serialize in declaration order: plain values first, then
/// tables, as TOML requires.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Entry {
    /// Stable identifier of the mod, referenced by `variants.toml`. Never changes.
    pub key: String,
    /// Path of the jar relative to the pack root, with `/` separators.
    pub path: String,
    #[serde(rename = "fileSize")]
    pub file_size: u64,
    /// Download URLs, as in a `.mrpack`. Empty when no platform hosts a
    /// redistributable copy.
    #[serde(default)]
    pub downloads: Vec<String>,
    /// Direct URL, last resort for a mod hosted on no platform.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub url: Option<String>,
    /// `local` for a jar tracked by git in `mods-local/`, at `path`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source: Option<Source>,
    /// sha512 of the local jar `modpack approve` approved for publication.
    /// The approval holds while it equals `hashes.sha512`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub approved: Option<String>,
    pub hashes: Hashes,
    #[serde(default)]
    pub env: Env,
    /// One table per platform, named after it. Read and written only by that
    /// platform's implementation.
    #[serde(flatten)]
    pub platforms: BTreeMap<String, toml::Table>,
}

/// Where the jar of a mod no platform hosts comes from.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Source {
    /// Tracked by git in the repository, under `mods-local/`.
    Local,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Hashes {
    pub sha1: String,
    pub sha512: String,
}

/// Which sides need the mod. A missing `env` means required on both, as in a
/// `.mrpack`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Env {
    pub client: Support,
    pub server: Support,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Support {
    #[default]
    Required,
    Optional,
    Unsupported,
}

impl Entry {
    /// The table of a platform, if the mod has one.
    pub fn platform(&self, name: &str) -> Option<&toml::Table> {
        self.platforms.get(name)
    }

    /// The table of a platform, created empty if missing.
    pub fn platform_mut(&mut self, name: &str) -> &mut toml::Table {
        self.platforms.entry(name.to_owned()).or_default()
    }

    /// Whether the jar is tracked by git in `mods-local/`.
    pub fn is_local(&self) -> bool {
        self.source == Some(Source::Local)
    }

    /// Whether a local mod's approval matches its jar as the manifest knows it.
    pub fn is_approved(&self) -> bool {
        self.approved.as_deref() == Some(self.hashes.sha512.as_str())
    }

    /// File name of the jar.
    pub fn file_name(&self) -> &str {
        self.path.rsplit('/').next().unwrap_or(&self.path)
    }

    /// Where the jar goes in an instance or a pack: `mods/<file name>`, for a
    /// local mod as for any other.
    pub fn instance_path(&self) -> String {
        format!("mods/{}", self.file_name())
    }
}

impl Manifest {
    /// An empty manifest for a pack.
    pub fn new(pack: Pack) -> Self {
        Self {
            pack,
            mods: Vec::new(),
        }
    }

    pub fn parse(text: &str) -> Result<Self> {
        let manifest: Self = super::parse_toml(text, FILE_NAME, HINT)?;
        let mut seen = BTreeSet::new();
        for entry in &manifest.mods {
            if !seen.insert(entry.key.as_str()) {
                return Err(Error::usage(
                    format!("{FILE_NAME} lists the key `{}` twice", entry.key),
                    HINT,
                ));
            }
        }
        Ok(manifest)
    }

    /// The canonical text of the manifest.
    pub fn to_toml(&self) -> String {
        let mut sorted = self.clone();
        sorted.mods.sort_by(|a, b| a.key.cmp(&b.key));
        format!("{HEADER}{}", super::to_toml(&sorted))
    }

    pub fn load(path: &Path) -> Result<Self> {
        Self::parse(&super::read_file(path)?)
    }

    pub fn save(&self, path: &Path) -> Result<()> {
        super::write_file(path, &self.to_toml())
    }

    pub fn get(&self, key: &str) -> Option<&Entry> {
        self.mods.iter().find(|e| e.key == key)
    }

    pub fn get_mut(&mut self, key: &str) -> Option<&mut Entry> {
        self.mods.iter_mut().find(|e| e.key == key)
    }

    pub fn keys(&self) -> BTreeSet<&str> {
        self.mods.iter().map(|e| e.key.as_str()).collect()
    }

    /// Adds the entry, or replaces the one with the same key.
    pub fn upsert(&mut self, entry: Entry) {
        match self.get_mut(&entry.key) {
            Some(existing) => *existing = entry,
            None => self.mods.push(entry),
        }
    }

    pub fn remove(&mut self, key: &str) -> Option<Entry> {
        let index = self.mods.iter().position(|e| e.key == key)?;
        Some(self.mods.remove(index))
    }

    /// Key for a new mod: the first of `slugs` that is not empty once
    /// normalized (Modrinth slug, then CurseForge slug, in the caller's order),
    /// else the jar name without version nor extension. A key already taken
    /// gets a numeric suffix. Existing entries keep their key: this is only
    /// for mods that have none yet.
    pub fn new_key(&self, slugs: &[Option<&str>], jar_name: &str) -> String {
        let base = slugs
            .iter()
            .flatten()
            .map(|s| normalize_key(s))
            .find(|k| !k.is_empty())
            .or_else(|| Some(normalize_key(&strip_jar_version(jar_name))).filter(|k| !k.is_empty()))
            .unwrap_or_else(|| "mod".to_owned());
        let taken = self.keys();
        if !taken.contains(base.as_str()) {
            return base;
        }
        (2..)
            .map(|n| format!("{base}-{n}"))
            .find(|k| !taken.contains(k.as_str()))
            .expect("an unbounded range always yields a free key")
    }
}

/// Lowercase, `a-z0-9` and single `-` between words.
pub fn normalize_key(raw: &str) -> String {
    let mut key = String::new();
    for c in raw.chars().flat_map(char::to_lowercase) {
        if c.is_ascii_alphanumeric() {
            key.push(c);
        } else if !key.is_empty() && !key.ends_with('-') {
            key.push('-');
        }
    }
    key.trim_end_matches('-').to_owned()
}

/// `sodium-fabric-0.5.11+mc1.21.jar` gives `sodium-fabric`: the name is cut at
/// the first word that looks like a version (starts with a digit, or with `v`
/// or `mc` followed by a digit).
fn strip_jar_version(jar_name: &str) -> String {
    let stem = jar_name
        .strip_suffix(".jar")
        .or_else(|| jar_name.strip_suffix(".JAR"))
        .unwrap_or(jar_name);
    let words: Vec<&str> = stem.split(['-', '_', ' ', '+']).collect();
    let is_version = |w: &str| {
        let rest = w
            .strip_prefix("mc")
            .or_else(|| w.strip_prefix('v'))
            .unwrap_or(w);
        rest.starts_with(|c: char| c.is_ascii_digit())
    };
    let kept: Vec<&str> = words
        .iter()
        .copied()
        .take_while(|w| !is_version(w))
        .collect();
    if kept.is_empty() {
        stem.to_owned()
    } else {
        kept.join("-")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fixture() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("tests/fixtures/repo")
            .join(FILE_NAME)
    }

    fn entry(key: &str) -> Entry {
        Entry {
            key: key.to_owned(),
            path: format!("mods/{key}-1.0.0.jar"),
            file_size: 42,
            downloads: vec![format!("https://cdn.example.org/{key}.jar")],
            url: None,
            source: None,
            approved: None,
            hashes: Hashes {
                sha1: "a".repeat(40),
                sha512: "b".repeat(128),
            },
            env: Env::default(),
            platforms: BTreeMap::new(),
        }
    }

    #[test]
    fn fixture_round_trips_byte_for_byte() {
        let text = std::fs::read_to_string(fixture()).unwrap();
        let manifest = Manifest::parse(&text).unwrap();
        assert!(manifest.mods.len() >= 4);
        assert_eq!(manifest.to_toml(), text);
    }

    #[test]
    fn save_then_load_gives_the_same_manifest() {
        let manifest = Manifest::load(&fixture()).unwrap();
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join(FILE_NAME);
        manifest.save(&path).unwrap();
        assert_eq!(Manifest::load(&path).unwrap(), manifest);
    }

    #[test]
    fn platform_tables_are_kept_as_written() {
        let manifest = Manifest::load(&fixture()).unwrap();
        let jei = manifest.get("jei").unwrap();
        let modrinth = jei.platform("modrinth").unwrap();
        assert!(modrinth.get("project_id").unwrap().is_str());
        let curseforge = jei.platform("curseforge").unwrap();
        assert!(curseforge.get("projectID").unwrap().is_integer());
        assert!(curseforge.get("fileID").unwrap().is_integer());
    }

    #[test]
    fn adding_an_entry_only_adds_its_lines() {
        let text = std::fs::read_to_string(fixture()).unwrap();
        let mut manifest = Manifest::parse(&text).unwrap();
        let mut new = entry("kotlin-for-forge");
        new.platform_mut("modrinth")
            .insert("project_id".into(), "ordsPcFz".into());
        manifest.upsert(new);
        let after = manifest.to_toml();

        let old: Vec<&str> = text.lines().collect();
        let new: Vec<&str> = after.lines().collect();
        let prefix = old.iter().zip(&new).take_while(|(a, b)| a == b).count();
        let suffix = old[prefix..]
            .iter()
            .rev()
            .zip(new[prefix..].iter().rev())
            .take_while(|(a, b)| a == b)
            .count();
        assert_eq!(prefix + suffix, old.len(), "no old line changed");
        let added = &new[prefix..new.len() - suffix];
        assert!(added.iter().any(|l| l.contains("kotlin-for-forge")));
        assert!(added.iter().all(|l| !l.contains("\"jei\"")));
    }

    #[test]
    fn output_is_sorted_by_key_and_header_comes_first() {
        let mut manifest = Manifest::new(Pack {
            minecraft: "1.21.1".into(),
            loader: "neoforge".into(),
            loader_version: "21.1.77".into(),
        });
        manifest.upsert(entry("zeta"));
        manifest.upsert(entry("alpha"));
        let text = manifest.to_toml();
        assert!(text.starts_with(HEADER));
        assert!(text.find("\"alpha\"").unwrap() < text.find("\"zeta\"").unwrap());
        assert!(text.contains("loader-version = \"21.1.77\""));
        assert!(text.contains("fileSize = 42"));
        assert!(!text.contains("url ="), "absent url is not written");
    }

    #[test]
    fn local_entry_round_trips_with_its_source_and_approval() {
        let mut manifest = Manifest::load(&fixture()).unwrap();
        let mut local = entry("custom");
        local.path = "mods-local/custom-1.0.jar".into();
        local.downloads.clear();
        local.source = Some(Source::Local);
        local.approved = Some("b".repeat(128));
        manifest.upsert(local);
        let text = manifest.to_toml();
        assert!(text.contains("source = \"local\"\n"), "{text}");
        let custom = Manifest::parse(&text)
            .unwrap()
            .get("custom")
            .unwrap()
            .clone();
        assert!(custom.is_local() && custom.is_approved());
        assert_eq!(custom.instance_path(), "mods/custom-1.0.jar");

        let mut changed = custom.clone();
        changed.hashes.sha512 = "c".repeat(128);
        assert!(!changed.is_approved());
        assert!(!manifest.get("jei").unwrap().is_local());
    }

    #[test]
    fn duplicate_keys_are_refused() {
        let mut manifest = Manifest::load(&fixture()).unwrap();
        let first = manifest.mods[0].clone();
        manifest.mods.push(first);
        let err = Manifest::parse(&manifest.to_toml()).unwrap_err();
        assert!(err.to_string().contains("twice"));
    }

    #[test]
    fn upsert_replaces_and_remove_removes() {
        let mut manifest = Manifest::load(&fixture()).unwrap();
        let count = manifest.mods.len();
        let mut jei = manifest.get("jei").unwrap().clone();
        jei.file_size = 1;
        manifest.upsert(jei);
        assert_eq!(manifest.mods.len(), count);
        assert_eq!(manifest.get("jei").unwrap().file_size, 1);
        assert!(manifest.remove("jei").is_some());
        assert!(manifest.get("jei").is_none());
        assert!(manifest.remove("jei").is_none());
    }

    #[test]
    fn key_prefers_slugs_in_order_then_jar_name() {
        let manifest = Manifest::new(Manifest::load(&fixture()).unwrap().pack);
        assert_eq!(
            manifest.new_key(&[Some("Fabric-API"), Some("fabric-api-cf")], "x.jar"),
            "fabric-api"
        );
        assert_eq!(
            manifest.new_key(&[None, Some("JustEnoughItems")], "x.jar"),
            "justenoughitems"
        );
        assert_eq!(
            manifest.new_key(&[None, None], "sodium-fabric-0.5.11+mc1.21.jar"),
            "sodium-fabric"
        );
        assert_eq!(
            manifest.new_key(&[], "Xaeros_Minimap_24.5.0_NeoForge_1.21.jar"),
            "xaeros-minimap"
        );
        assert_eq!(
            manifest.new_key(&[], "appleskin-neoforge-mc1.21-3.0.5.jar"),
            "appleskin-neoforge"
        );
        assert_eq!(manifest.new_key(&[], "1.0.0.jar"), "1-0-0");
        assert_eq!(manifest.new_key(&[Some("__")], "!!!.jar"), "mod");
    }

    #[test]
    fn key_collision_gets_a_numeric_suffix() {
        let mut manifest = Manifest::load(&fixture()).unwrap();
        assert_eq!(manifest.new_key(&[Some("jei")], "x.jar"), "jei-2");
        manifest.upsert(entry("jei-2"));
        assert_eq!(manifest.new_key(&[Some("jei")], "x.jar"), "jei-3");
    }

    #[test]
    fn normalize_key_keeps_lowercase_alphanumerics_and_dashes() {
        assert_eq!(normalize_key("  Iris Shaders!! "), "iris-shaders");
        assert_eq!(normalize_key("a__b--c"), "a-b-c");
        assert_eq!(normalize_key("Été"), "t");
    }
}
