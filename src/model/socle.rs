//! `.modpack/socle.toml` and `.modpack/socle.lock`: the socle's own records
//! in the repository.
//!
//! The socle version is the version of the CLI that last wrote the socle:
//! every command compares it to its own.

use std::cmp::Ordering;
use std::path::Path;

use semver::Version;
use serde::{Deserialize, Serialize};

use crate::error::{Error, Result};

/// Path of the socle settings, relative to the repository root.
pub const CONFIG_PATH: &str = ".modpack/socle.toml";
/// Path of the registry, relative to the repository root.
pub const LOCK_PATH: &str = ".modpack/socle.lock";

const CONFIG_HEADER: &str =
    "# Managed by modpack-cli. `modpack update` rewrites the version and keeps the values.\n\n";
const LOCK_HEADER: &str =
    "# Generated by modpack-cli: files the socle wrote. Do not edit by hand.\n\n";

/// `.modpack/socle.toml`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SocleConfig {
    /// Version of the CLI that last wrote the socle.
    pub version: String,
    pub init: InitValues,
}

/// Values given to `modpack init`, kept by every update.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub struct InitValues {
    pub name: String,
    pub minecraft: String,
    pub loader: String,
    pub loader_version: String,
    pub author: String,
}

impl SocleConfig {
    pub fn parse(text: &str) -> Result<Self> {
        super::parse_toml(
            text,
            CONFIG_PATH,
            "restore it from git history, or rerun `modpack init` in a new directory",
        )
    }

    pub fn to_toml(&self) -> String {
        format!("{CONFIG_HEADER}{}", super::to_toml(self))
    }

    /// Reads `.modpack/socle.toml` under the repository root.
    pub fn load(root: &Path) -> Result<Self> {
        Self::parse(&super::read_file(&root.join(CONFIG_PATH))?)
    }

    pub fn save(&self, root: &Path) -> Result<()> {
        super::write_file(&root.join(CONFIG_PATH), &self.to_toml())
    }
}

/// `.modpack/socle.lock`.
#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SocleLock {
    #[serde(default)]
    pub files: Vec<LockedFile>,
}

/// One thing the socle wrote.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockedFile {
    /// Path relative to the repository root, with `/` separators.
    pub path: String,
    /// sha256 of what the socle wrote: the whole file, or the block between
    /// its markers.
    pub sha256: String,
    pub kind: LockedKind,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum LockedKind {
    /// A file the socle owns entirely.
    File,
    /// A block between markers in a file the pack owns otherwise.
    Block,
}

impl SocleLock {
    pub fn parse(text: &str) -> Result<Self> {
        super::parse_toml(
            text,
            LOCK_PATH,
            "restore it from git history; `modpack update --force` rewrites it",
        )
    }

    /// The canonical text, sorted by path.
    pub fn to_toml(&self) -> String {
        let mut sorted = self.clone();
        sorted.files.sort_by(|a, b| a.path.cmp(&b.path));
        format!("{LOCK_HEADER}{}", super::to_toml(&sorted))
    }

    pub fn load(root: &Path) -> Result<Self> {
        Self::parse(&super::read_file(&root.join(LOCK_PATH))?)
    }

    pub fn save(&self, root: &Path) -> Result<()> {
        super::write_file(&root.join(LOCK_PATH), &self.to_toml())
    }
}

/// How the repository's socle version compares to the CLI's.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum VersionCheck {
    Equal,
    /// The repository can be brought to the CLI's version with `modpack update`.
    RepoOlder {
        repo: Version,
        cli: Version,
    },
    /// The CLI does not know this socle's format yet.
    RepoNewer {
        repo: Version,
        cli: Version,
    },
}

/// Version of this CLI, which is also the version of the socle it writes.
pub fn cli_version() -> Version {
    Version::parse(env!("CARGO_PKG_VERSION")).expect("the crate version is semver")
}

/// Compares the repository's socle version to `cli`.
pub fn compare_versions(repo: &str, cli: &Version) -> Result<VersionCheck> {
    let repo = Version::parse(repo).map_err(|e| {
        Error::usage(
            format!("{CONFIG_PATH} has an invalid version `{repo}`"),
            "restore the file from git history",
        )
        .with_source(e)
    })?;
    Ok(match repo.cmp(cli) {
        Ordering::Equal => VersionCheck::Equal,
        Ordering::Less => VersionCheck::RepoOlder {
            repo,
            cli: cli.clone(),
        },
        Ordering::Greater => VersionCheck::RepoNewer {
            repo,
            cli: cli.clone(),
        },
    })
}

impl VersionCheck {
    /// What a command does about it: nothing, a warning to show, or a refusal.
    pub fn enforce(&self) -> Result<Option<String>> {
        match self {
            VersionCheck::Equal => Ok(None),
            VersionCheck::RepoOlder { repo, cli } => Ok(Some(format!(
                "this repository uses socle {repo}, older than this CLI ({cli}); run `modpack update` to bring it up to date"
            ))),
            VersionCheck::RepoNewer { repo, cli } => Err(Error::usage(
                format!(
                    "this repository uses socle {repo}, newer than this CLI ({cli}), which does not know its format"
                ),
                format!("upgrade modpack-cli to {repo} or later"),
            )),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::error::ErrorKind;

    fn fixture_root() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/repo")
    }

    fn v(s: &str) -> Version {
        Version::parse(s).unwrap()
    }

    #[test]
    fn config_fixture_round_trips() {
        let text = std::fs::read_to_string(fixture_root().join(CONFIG_PATH)).unwrap();
        let config = SocleConfig::parse(&text).unwrap();
        assert_eq!(config.init.loader, "neoforge");
        assert_eq!(config.to_toml(), text);
    }

    #[test]
    fn lock_fixture_round_trips_and_matches_the_files() {
        let root = fixture_root();
        let text = std::fs::read_to_string(root.join(LOCK_PATH)).unwrap();
        let lock = SocleLock::parse(&text).unwrap();
        assert_eq!(lock.to_toml(), text);
        let file = lock
            .files
            .iter()
            .find(|f| f.kind == LockedKind::File)
            .unwrap();
        assert_eq!(
            crate::model::sha256_file(&root.join(&file.path)).unwrap(),
            file.sha256
        );
        assert!(lock.files.iter().any(|f| f.kind == LockedKind::Block));
    }

    #[test]
    fn save_then_load() {
        let dir = tempfile::tempdir().unwrap();
        let config = SocleConfig::load(&fixture_root()).unwrap();
        config.save(dir.path()).unwrap();
        assert_eq!(SocleConfig::load(dir.path()).unwrap(), config);
        let lock = SocleLock::load(&fixture_root()).unwrap();
        lock.save(dir.path()).unwrap();
        assert_eq!(SocleLock::load(dir.path()).unwrap(), lock);
    }

    #[test]
    fn lock_is_written_sorted_by_path() {
        let entry = |path: &str| LockedFile {
            path: path.into(),
            sha256: "0".repeat(64),
            kind: LockedKind::File,
        };
        let lock = SocleLock {
            files: vec![entry("b"), entry("a")],
        };
        let text = lock.to_toml();
        assert!(text.find("path = \"a\"").unwrap() < text.find("path = \"b\"").unwrap());
    }

    #[test]
    fn equal_versions_say_nothing() {
        let check = compare_versions("0.3.0", &v("0.3.0")).unwrap();
        assert_eq!(check, VersionCheck::Equal);
        assert_eq!(check.enforce().unwrap(), None);
    }

    #[test]
    fn older_repository_warns_and_suggests_update() {
        let check = compare_versions("0.2.9", &v("0.3.0")).unwrap();
        assert!(matches!(check, VersionCheck::RepoOlder { .. }));
        let warning = check.enforce().unwrap().unwrap();
        assert!(warning.contains("modpack update"));
    }

    #[test]
    fn newer_repository_is_refused() {
        let check = compare_versions("0.4.0", &v("0.3.0")).unwrap();
        assert!(matches!(check, VersionCheck::RepoNewer { .. }));
        let err = check.enforce().unwrap_err();
        assert!(err.to_string().contains("newer than this CLI"));
    }

    #[test]
    fn prereleases_order_before_their_release() {
        let check = compare_versions("0.3.0-rc1", &v("0.3.0")).unwrap();
        assert!(matches!(check, VersionCheck::RepoOlder { .. }));
    }

    #[test]
    fn invalid_version_is_reported() {
        let err = compare_versions("latest", &v("0.3.0")).unwrap_err();
        assert_eq!(err.kind(), ErrorKind::Usage);
        assert!(err.to_string().contains("`latest`"));
    }

    #[test]
    fn cli_version_is_the_crate_version() {
        assert_eq!(cli_version().to_string(), env!("CARGO_PKG_VERSION"));
    }
}
